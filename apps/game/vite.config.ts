import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vite';
import { VitePWA } from 'vite-plugin-pwa';
import assetManifestPlugin from './plugins/asset-manifest';
import devReviewAssetsPlugin from './plugins/dev-review-assets';
import voiceBoothPlugin from './plugins/voice-booth';
import pruneDevOnlyPlugin from './plugins/prune-dev-only';
import cacheNamesPlugin, { ART, CLEANUP_FILE, VOICE, cacheNames, devCacheNames } from './plugins/cache-names';

export default defineConfig(({ command }) => {
  // The art and voice caches are named after a hash of the files in them (plugins/cache-names.ts),
  // so a release that changes a sprite or a voice line starts a fresh cache for it and one that
  // does not keeps the old one. Hashing about 100 MB takes a second: only a real build needs it.
  const publicDir = fileURLToPath(new URL('./public', import.meta.url));
  const names = command === 'build' ? cacheNames(publicDir) : devCacheNames();

  return {
    plugins: [
      assetManifestPlugin(),
      devReviewAssetsPlugin(),
      // Dev only: the voice booth's save endpoint (voice-takes/), and it takes the
      // booth page out of every production build. See docs/voice-recording-plan-2026-10-14.md.
      voiceBoothPlugin(),
      // Build only: leaves the dev-only pages (plugins/prune-list.mjs) out of the output.
      pruneDevOnlyPlugin(),
      cacheNamesPlugin(names),
      VitePWA({
        registerType: 'autoUpdate',
        manifest: {
          name: 'A.R.C. — Animal Rescue Centre',
          short_name: 'A.R.C.',
          description: 'Run your own animal rescue centre!',
          theme_color: '#4a9c5d',
          background_color: '#fef9ef',
          display: 'standalone',
          orientation: 'landscape',
          // Generated by scripts/generate-icons.mjs from the Interfulgent
          // suite mark, assets/logo/arc-suite-icon.svg (2026-10-06).
          // These were 11-byte "placeholder" text files until 2026-08-27.
          //
          // theme_color and background_color stay the game's own greens and
          // cream. They dress the browser chrome and the PWA splash, which
          // belong to the app; the suite ground (#0D0D1F) belongs to the icon.
          icons: [
            {
              src: '/icons/icon-192.png',
              sizes: '192x192',
              type: 'image/png',
            },
            {
              src: '/icons/icon-512.png',
              sizes: '512x512',
              type: 'image/png',
            },
            {
              src: '/icons/icon-512-maskable.png',
              sizes: '512x512',
              type: 'image/png',
              purpose: 'maskable',
            },
          ],
        },
        workbox: {
          // PRECACHE = app shell only.
          //
          // Globbing the art folders too built a 1124-entry / 454 MB precache
          // manifest. A service worker installs all-or-nothing, so on iOS —
          // where the per-origin quota is a small fraction of that — install
          // failed, the worker never activated, offline never worked, and the
          // whole download was retried on every visit.
          //
          // The art is already tiered by AssetLoader (boot → essential →
          // variant), so precaching it duplicated that work and fought it.
          // Now the shell precaches (~2 MB) and art lands in the runtime
          // caches below as the game actually asks for it — which means
          // anything the player has already seen still works offline.
          globPatterns: ['**/*.{js,css,html,woff2}', 'icons/*.png', 'favicon.svg'],
          globIgnores: ['admin/**', 'mockups/**', CLEANUP_FILE],
          // Runs on activate and deletes the art and voice caches of earlier releases (plugins/cache-names.ts).
          importScripts: [CLEANUP_FILE],
          maximumFileSizeToCacheInBytes: 8 * 1024 * 1024,
          runtimeCaching: [
            {
              // Game art. Art keeps its file name when it is redrawn, so the cache is
              // named after a hash of the art files' contents: cache-first within a
              // release, and a release that changes art starts a fresh cache and
              // the cleanup script removes the old one. The extensions here are the
              // ones plugins/cache-names.ts hashes (ART); change both together.
              urlPattern: /\/assets\/.*\.(?:png|jpg|jpeg|webp|svg)$/,
              handler: 'CacheFirst',
              options: {
                cacheName: names[ART.prefix],
                expiration: { maxEntries: 1200, maxAgeSeconds: 60 * 60 * 24 * 60 },
                cacheableResponse: { statuses: [0, 200] },
              },
            },
            {
              // Recorded voice lines (assets/voice/<line id>.mp3). Their own cache,
              // listed before the general audio one so it matches first: a hundred
              // clips in the 80-entry audio cache would push the music out.
              // Named after a hash of the voice files, like the art (cache-names.ts,
              // VOICE): a re-recorded line keeps its file name, so without this a
              // returning player would hear the old take for up to 60 days.
              urlPattern: /\/assets\/voice\/.*\.mp3$/,
              handler: 'CacheFirst',
              options: {
                cacheName: names[VOICE.prefix],
                expiration: { maxEntries: 200, maxAgeSeconds: 60 * 60 * 24 * 60 },
                cacheableResponse: { statuses: [0, 200] },
              },
            },
            {
              urlPattern: /\/assets\/.*\.(?:mp3|ogg|wav|webm)$/,
              handler: 'CacheFirst',
              options: {
                cacheName: 'arc-audio',
                expiration: { maxEntries: 80, maxAgeSeconds: 60 * 60 * 24 * 60 },
                cacheableResponse: { statuses: [0, 200] },
              },
            },
            {
              // Overlay pages and the cast/map art they pull in. Revalidating
              // keeps an edited overlay fresh without blocking the open.
              urlPattern: /\/admin\/.*/,
              handler: 'StaleWhileRevalidate',
              options: {
                cacheName: 'arc-overlays',
                expiration: { maxEntries: 300, maxAgeSeconds: 60 * 60 * 24 * 30 },
                cacheableResponse: { statuses: [0, 200] },
              },
            },
            {
              // Manifest + anchor data — small, and changes with each deploy.
              urlPattern: /\/(?:asset-manifest\.json|data\/.*\.json)$/,
              handler: 'StaleWhileRevalidate',
              options: {
                cacheName: 'arc-data',
                expiration: { maxEntries: 30 },
                cacheableResponse: { statuses: [0, 200] },
              },
            },
          ],
          // Don't let the SPA app-shell fallback hijack admin tools, JSON data
          // files, or the 404 page — we want the real file (or Vercel's 404) to
          // win for these routes instead of returning index.html from cache.
          navigateFallbackDenylist: [
            /^\/admin\//,
            /^\/data\//,
            /^\/404\.html$/,
          ],
        },
      }),
    ],
    build: {
      target: 'es2022',
      // Split Phaser (big, rarely changes) into its own chunk so the app shell
      // stays small and the engine caches independently across deploys.
      rollupOptions: {
        output: {
          manualChunks(id) {
            if (id.includes('node_modules/phaser')) return 'phaser';
            if (id.includes('node_modules')) return 'vendor';
          },
        },
      },
      chunkSizeWarningLimit: 1500,
    },
  };
});

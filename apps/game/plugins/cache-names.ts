/**
 * The service worker's art and voice caches, named after what is in them.
 *
 * sw.js is generated (vite-plugin-pwa, workbox generateSW, configured in
 * vite.config.ts); there is no hand-written one. Its art route and its voice
 * route are cache-first with a 60 day lifetime, and a file keeps its name when
 * it is redrawn or re-recorded (assets/animals/cat.png is cat.png after a
 * restyle; assets/voice/<line>.mp3 is the same after a new take). So a returning
 * player kept the old drawing or the old voice for up to 60 days.
 *
 * Fix: each cache's name carries a hash of its files' contents. A release that
 * changes a sprite gets a new art name, one that changes a voice line gets a new
 * voice name, and the new service worker starts an empty cache and the player
 * downloads that family again, once. A release with no change in a family computes
 * the same name, so its cache is kept and nothing is downloaded. The old cache
 * would sit there until its 60 days ran out, so this also emits a small script
 * (CLEANUP_FILE) that sw.js imports; it deletes every older cache of each family
 * when the new worker activates. Workbox's own cleanup only knows its precache,
 * not runtime caches.
 *
 * Only art and voice are hashed here, and each by the extensions its route in
 * vite.config.ts matches. Audio, overlays and data keep their fixed cache names:
 * the audio and the overlays are revalidated or rarely change, and a hash for
 * them would be a decision for someone to make on purpose (see vite.config.ts).
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';

export const CLEANUP_FILE = 'sw-cache-cleanup.js';

/** A family of files that share one runtime cache. */
export interface CacheFamily {
  /** The cache's name before the hash. */
  prefix: string;
  /** Where its files are, relative to public/. */
  dir: string;
  /** Which files in that folder belong to it: the extensions its route in vite.config.ts matches. */
  match: RegExp;
}

/** The art route: /assets/**.(png|jpg|jpeg|webp|svg). */
export const ART: CacheFamily = { prefix: 'arc-art', dir: 'assets', match: /\.(?:png|jpe?g|webp|svg)$/i };
/** The voice route: /assets/voice/**.mp3 (written by apps/game/tools/voice-publish.mjs). */
export const VOICE: CacheFamily = { prefix: 'arc-voice', dir: 'assets/voice', match: /\.mp3$/i };

export const FAMILIES: CacheFamily[] = [ART, VOICE];

/** The cache names a build uses, by prefix: { 'arc-art': 'arc-art-0123456789ab', ... }. */
export type CacheNames = Record<string, string>;

function* walk(dir: string): Generator<string> {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (entry.isFile()) yield full;
  }
}

/**
 * sha256 over every matching file's path and content hash, in path order. The
 * modification time plays no part, so a fresh checkout hashes the same as the
 * checkout before it. A folder with no files (voice, before the first line is
 * published) has a hash too: the hash of nothing.
 */
export function contentHash(dir: string, match: RegExp): string {
  const lines: string[] = [];
  if (fs.existsSync(dir)) {
    for (const file of walk(dir)) {
      if (!match.test(file)) continue;
      const rel = path.relative(dir, file).split(path.sep).join('/');
      const content = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
      lines.push(`${rel}\0${content}`);
    }
  }
  lines.sort();
  return crypto.createHash('sha256').update(lines.join('\n')).digest('hex');
}

/** `<prefix>-<12 hex>` for one family under <publicDir>. */
export function cacheName(publicDir: string, family: CacheFamily): string {
  return `${family.prefix}-${contentHash(path.join(publicDir, family.dir), family.match).slice(0, 12)}`;
}

/** Every family's name for a real build. */
export function cacheNames(publicDir: string): CacheNames {
  return Object.fromEntries(FAMILIES.map((f) => [f.prefix, cacheName(publicDir, f)]));
}

/** The names for `vite` (dev server): nothing is hashed, and no service worker is generated. */
export function devCacheNames(): CacheNames {
  return Object.fromEntries(FAMILIES.map((f) => [f.prefix, `${f.prefix}-dev`]));
}

/** The text of CLEANUP_FILE for a build whose caches are `current`. */
export function cleanupScript(current: CacheNames): string {
  return `// Generated by apps/game/plugins/cache-names.ts at build time. Imported by sw.js.
// The art and voice caches are named after a hash of what is in them. When this service worker takes
// over, drop every older cache of each family, and the unversioned ones that earlier releases used.
const CURRENT = ${JSON.stringify(current)};
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(
        names
          .filter((name) =>
            Object.keys(CURRENT).some(
              (prefix) => (name === prefix || name.startsWith(prefix + '-')) && name !== CURRENT[prefix],
            ),
          )
          .map((name) => caches.delete(name)),
      ),
    ),
  );
});
`;
}

/** Emits CLEANUP_FILE into every build. The names are the ones vite.config.ts gave the routes. */
export default function cacheNamesPlugin(current: CacheNames): Plugin {
  return {
    name: 'arc-cache-names',
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: CLEANUP_FILE, source: cleanupScript(current) });
    },
  };
}

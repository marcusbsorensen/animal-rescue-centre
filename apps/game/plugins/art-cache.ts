/**
 * The service worker's art cache, named after the art in it.
 *
 * sw.js is generated (vite-plugin-pwa, workbox generateSW, configured in
 * vite.config.ts); there is no hand-written one. Its art route is cache-first
 * with a 60 day lifetime, and art keeps its file name when it is redrawn
 * (assets/animals/cat.png is cat.png after a restyle too). So a returning
 * player kept the old drawings for up to 60 days.
 *
 * Fix: the cache's name carries a hash of the art files' contents. A release
 * that changes a sprite gets a new name, so the new service worker starts an
 * empty cache and the player downloads art again, once. A release with no art
 * change computes the same name, so the cache is kept and nothing is downloaded.
 * The old cache would sit there until its 60 days ran out, so this also emits a
 * small script (CLEANUP_FILE) that sw.js imports; it deletes every older art
 * cache when the new worker activates. Workbox's own cleanup only knows its
 * precache, not runtime caches.
 *
 * Only art is hashed here: the extensions the art route in vite.config.ts
 * matches, under public/assets/. Audio, voice lines, overlays and data keep their
 * fixed cache names (see the notes in vite.config.ts).
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';

export const ART_CACHE_PREFIX = 'arc-art';
export const CLEANUP_FILE = 'sw-art-cleanup.js';

/** The extensions the service worker's art route matches (vite.config.ts urlPattern). */
const ART_FILE = /\.(?:png|jpe?g|webp|svg)$/i;

function* walk(dir: string): Generator<string> {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (entry.isFile()) yield full;
  }
}

/**
 * sha256 over every art file's path and content hash, in path order. The
 * modification time plays no part, so a fresh checkout hashes the same as the
 * checkout before it.
 */
export function artContentHash(assetsDir: string): string {
  const lines: string[] = [];
  if (fs.existsSync(assetsDir)) {
    for (const file of walk(assetsDir)) {
      if (!ART_FILE.test(file)) continue;
      const rel = path.relative(assetsDir, file).split(path.sep).join('/');
      const content = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
      lines.push(`${rel}\0${content}`);
    }
  }
  lines.sort();
  return crypto.createHash('sha256').update(lines.join('\n')).digest('hex');
}

/** `arc-art-<12 hex>` for the art under <publicDir>/assets. */
export function artCacheName(publicDir: string): string {
  return `${ART_CACHE_PREFIX}-${artContentHash(path.join(publicDir, 'assets')).slice(0, 12)}`;
}

/** The text of CLEANUP_FILE for a build whose art cache is `current`. */
export function cleanupScript(current: string): string {
  return `// Generated by apps/game/plugins/art-cache.ts at build time. Imported by sw.js.
// The art cache is named after a hash of the art in it. When this service worker takes over, drop
// every older art cache, and the unversioned "${ART_CACHE_PREFIX}" that earlier releases used.
const ART_CACHE = ${JSON.stringify(current)};
const PREFIX = ${JSON.stringify(ART_CACHE_PREFIX)};
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(
        names
          .filter((name) => (name === PREFIX || name.startsWith(PREFIX + '-')) && name !== ART_CACHE)
          .map((name) => caches.delete(name)),
      ),
    ),
  );
});
`;
}

/** Emits CLEANUP_FILE into every build. The name is the one vite.config.ts gave the art route. */
export default function artCachePlugin(current: string): Plugin {
  return {
    name: 'arc-art-cache',
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: CLEANUP_FILE, source: cleanupScript(current) });
    },
  };
}

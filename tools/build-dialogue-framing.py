#!/usr/bin/env python3
"""
Work out each dialogue portrait's waist-up crop and write it as a TypeScript table.

The cast portraits are 512x512 full-figure catalogue shots, and Marnie's two
are already waist-up. The dialogue stands a portrait on the edge of the box at
55-65% of the screen height, so a full figure would shrink to a sliver or run
behind the box with its legs hanging in the air. This script measures each
picture's figure (the bounding box of its opaque pixels) and decides how much of
it to show:

  - Marnie: the whole figure, trimmed of empty margin.
  - everyone else: from the top of the figure down to a fraction of its height.
    The default is WAIST_UP (a little below the waist, where Marnie's own
    pictures end). OVERRIDES lists the households where the default is wrong:

      01-priya      she is in a wheelchair. The crop ends at the chair's arm
                    rests: the chair's back and push handles show, the hands
                    on her lap show, and the wheels start just below the cut
                    instead of being sliced through by the dialogue box.
      crowds        a family with small children, or a whole train of them,
                    shows further down so the children's faces and shoulders
                    are in frame.

Output: apps/game/src/ui/dialogue-framing.ts (do not edit by hand; edit
OVERRIDES here and rerun).

    python3 tools/build-dialogue-framing.py
    python3 tools/build-dialogue-framing.py --sheet /tmp/crops.jpg   # review sheet
"""
import argparse
import glob
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAST = os.path.join(ROOT, "apps/game/public/admin/scene-assets/cast")
OUT = os.path.join(ROOT, "apps/game/src/ui/dialogue-framing.ts")

WAIST_UP = 0.58
HEADROOM_PX = 6
SIDE_PAD_PX = 5

# Fraction of the figure's height to show, where WAIST_UP is wrong.
OVERRIDES = {
    "01-priya": 0.57,
    "01-priya-greeting": 0.58,
    # Groups with small children standing in front of the adults.
    "07-patel-greens": 0.62,
    "09-okonkwo-harts": 0.62,
    "11-vargas-chen": 0.64,
    "13-kumar-ishii": 0.62,
    "14-theo-grandkids": 0.62,
    "15-khans": 0.64,
    "24-perera-fernando": 0.64,
    "30-two-houses": 0.64,
    # Rows of people of similar height, and a crowd of children.
    "25-bramble-house": 0.74,
    "31-estrada-train": 0.74,
}


def sources():
    """(key, path, kind) for every portrait the dialogue can draw."""
    out = []
    for name in ("warden-marnie", "warden-marnie-happy"):
        out.append((name, os.path.join(CAST, name + ".png"), "warden"))
    for path in sorted(glob.glob(os.path.join(CAST, "[0-9][0-9]-*.png"))):
        key = os.path.basename(path)[:-4]
        if "-with-" in key or key.endswith("-greeting"):
            continue
        out.append((key, path, "adopter"))
    for path in sorted(glob.glob(os.path.join(CAST, "variants", "[0-9][0-9]-*-greeting.png"))):
        out.append((os.path.basename(path)[:-4], path, "adopter"))
    return out


def frame(key, path, kind):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    x0, y0, x1, y1 = im.getchannel("A").getbbox()
    # A greeting variant is the same household, so it takes the same exception.
    base = key[: -len("-greeting")] if key.endswith("-greeting") else key
    frac = 1.0 if kind == "warden" else OVERRIDES.get(key, OVERRIDES.get(base, WAIST_UP))
    top = max(0, y0 - HEADROOM_PX)
    bottom = min(h, y0 + round((y1 - y0) * frac))
    left = max(0, x0 - SIDE_PAD_PX)
    right = min(w, x1 + SIDE_PAD_PX)
    return (left / w, top / h, (right - left) / w, (bottom - top) / h), (left, top, right, bottom), im


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheet", help="also write a JPEG contact sheet of the crops")
    args = ap.parse_args()

    rows = []
    sheet_tiles = []
    for key, path, kind in sources():
        frac, box, im = frame(key, path, kind)
        rows.append((key, frac))
        sheet_tiles.append((key, im.crop(box)))

    lines = [
        "// GENERATED by tools/build-dialogue-framing.py. Do not edit by hand.",
        "//",
        "// Each dialogue portrait's waist-up crop, as fractions of the source",
        "// picture: [x, y, w, h]. See the tool for the rule and the exceptions.",
        "",
        "export type PortraitCrop = readonly [x: number, y: number, w: number, h: number];",
        "",
        "export const DIALOGUE_CROPS: Readonly<Record<string, PortraitCrop>> = {",
    ]
    for key, (x, y, w, h) in rows:
        lines.append(f"  '{key}': [{x:.4f}, {y:.4f}, {w:.4f}, {h:.4f}],")
    lines += [
        "};",
        "",
        "/** The crop for a portrait file or URL (`.../01-priya.png`), if one is on record. */",
        "export function portraitCropFor(fileOrUrl: string): PortraitCrop | undefined {",
        "  const base = fileOrUrl.split('?')[0].split('/').pop()?.replace(/\\.[a-z]+$/i, '') ?? '';",
        "  return DIALOGUE_CROPS[base];",
        "}",
        "",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} ({len(rows)} portraits)")

    if args.sheet:
        cell_w, cell_h, cols = 88, 96, 10
        rws = (len(sheet_tiles) + cols - 1) // cols
        sheet = Image.new("RGB", (cols * cell_w, rws * cell_h), (225, 238, 243))
        d = ImageDraw.Draw(sheet)
        for i, (key, tile) in enumerate(sheet_tiles):
            s = min((cell_w - 6) / tile.width, (cell_h - 14) / tile.height)
            t = tile.resize((max(1, int(tile.width * s)), max(1, int(tile.height * s))))
            x = (i % cols) * cell_w
            y = (i // cols) * cell_h
            sheet.paste(t, (x + (cell_w - t.width) // 2, y + cell_h - 2 - t.height), t)
            d.text((x + 2, y + 1), key[:9], fill=(20, 40, 60))
        sheet.save(args.sheet, quality=62)
        print("sheet:", args.sheet, sheet.size)


if __name__ == "__main__":
    sys.exit(main())
